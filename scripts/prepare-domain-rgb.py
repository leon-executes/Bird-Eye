"""Prepare RGB pool from pinned NWPU caption splits; protect held-out images first.
No labels are generated by a VLM. Near-duplicate screening is not geographic proof.
"""
import json,hashlib,io,collections,re
from pathlib import Path
import pyarrow.parquet as pq
from PIL import Image
ROOT=Path.cwd();OUT=ROOT/'data/domain-adaptation';OUT.mkdir(exist_ok=True);(OUT/'rgb').mkdir(exist_ok=True)
def write(name,obj):(OUT/name).write_text(json.dumps(obj,indent=2),encoding='utf-8')
def sha(b):return hashlib.sha256(b).hexdigest()
def dhash(im):
 pixels=list(im.convert('L').resize((9,8),Image.Resampling.BILINEAR).getdata());h=0
 for y in range(8):
  for x in range(8):h=(h<<1)|int(pixels[y*9+x]>pixels[y*9+x+1])
 return h
class NearIndex:
 def __init__(self):self.buckets=collections.defaultdict(list);self.hashes=[]
 def find(self,h):
  candidates=set()
  for i in range(5):candidates.update(self.buckets[(i,(h>>(i*13))&8191)])
  return next((j for j in candidates if (self.hashes[j]^h).bit_count()<=4),None)
 def add(self,h):
  j=len(self.hashes);self.hashes.append(h)
  for i in range(5):self.buckets[(i,(h>>(i*13))&8191)].append(j)
index=NearIndex();blocked=set();excluded=collections.Counter();val=[];train=[];protected=[]
for file in ['data/manifest.json','data/imports.json']:
 if not (ROOT/file).exists():continue
 v=json.loads((ROOT/file).read_text());scenes=v.get('scenes',[]) if isinstance(v,dict) else v
 for s in scenes:
  for a in s['assets']:
   p=ROOT/'data'/a['path'];b=p.read_bytes();im=Image.open(io.BytesIO(b));h=dhash(im);index.add(h);blocked.add(sha(b));protected.append({'sha256':sha(b),'dhash':format(h,'016x'),'source':'existing evaluation/user image'})
for row in json.loads((ROOT/'data/adaptation/pilot-evaluation.json').read_text()):
 b=(ROOT/row['image']).read_bytes();h=dhash(Image.open(io.BytesIO(b)));index.add(h);blocked.add(sha(b));protected.append({'sha256':sha(b),'dhash':format(h,'016x'),'source':'development regression'})
for split in ['test','validation','train']:
 for parquet in sorted((ROOT/'data/corpora/nwpu').glob(split+'-*.parquet')):
  for batch in pq.ParquetFile(parquet).iter_batches(batch_size=256):
   for row in batch.to_pylist():
    b=row['image']['bytes'];im=Image.open(io.BytesIO(b)).convert('RGB');h=dhash(im);digest=sha(b)
    refs=list(dict.fromkeys(row['caption_'+str(i)].strip() for i in range(1,6) if isinstance(row['caption_'+str(i)],str)))
    captions=[x for x in refs if 8<=len(x.split())<=70 and len(x)<500 and not re.search(r'\b(moving|driving|travelling|traveling|running|walking|waiting|working|busy|normal traffic|emitting smoke|military|north|south|east|west)\b',x,re.I)]
    if split=='test':index.add(h);blocked.add(digest);protected.append({'sha256':digest,'dhash':format(h,'016x'),'source':'NWPU official test'});continue
    if digest in blocked or index.find(h) is not None:excluded[split+'_near_or_exact_duplicate']+=1;continue
    index.add(h);blocked.add(digest)
    if split=='validation':protected.append({'sha256':digest,'dhash':format(h,'016x'),'source':'NWPU official validation'})
    if not captions:excluded[split+'_caption_length']+=1;continue
    if split=='validation' and len(val)>=256:continue
    name=row['file_name'];dest=OUT/'rgb'/name
    if dest.name!=name:raise ValueError('Unexpected image path')
    dest.write_bytes(b)
    record={'id':'nwpu-'+Path(name).stem,'image':dest.relative_to(ROOT).as_posix(),'sha256':digest,'dhash':format(h,'016x'),'caption':captions[0],'references':refs,'eligible_references':captions,'modality':'RGB','source':{'dataset':'NWPU-Captions','repo':'caglarmert/NWPU-captions','revision':'80bbaf1ef145c7279b1e2de933689c8add174606','split':split,'original_id':name},'label_origin':'human captions; unedited; exclude explicit motion/activity, smoke-source and cardinal-direction assertions'}
    (val if split=='validation' else train).append(record)
  print(split,parquet.name,'train',len(train),'val',len(val),flush=True)
write('rgb-train.json',train);write('rgb-validation.json',val);write('protected-hashes.json',protected);write('rgb-preparation.json',{'train':len(train),'validation':len(val),'excluded':dict(excluded),'source':'https://huggingface.co/datasets/caglarmert/NWPU-captions','rights':'Local research only; source-image and original dataset rights apply. No image/weight redistribution permission inferred from mirror availability.','selection':'All eligible official training images; exact-byte and dHash<=4 screened against all official test and validation and existing user/evaluation images, then earlier training images.','caption_filter':'8-70 words, under 500 characters; excludes explicit moving/driving/travelling/running/walking/waiting/working/busy, normal traffic, emitting smoke, military and cardinal-direction assertions. This is screening, not a truth guarantee.','limits':['Public pretraining overlap unknown.','Perceptual hash screening does not establish geographic or capture-sequence independence.','Human captions can still contain errors.']});print('RGB READY',len(train),len(val),dict(excluded),flush=True)
